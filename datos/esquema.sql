-- =====================================================================
-- ESQUEMA DE LA BASE DE DATOS · MultiBar (plataforma de autonomIA Lab)
-- ---------------------------------------------------------------------
-- Base: proyecto Supabase "multi-bar" (Frankfurt), separado de El Recreo
-- (antes, Neon "la-mar-de-gambas"). Los roles de la web son los de
-- Supabase: "anon" (visitante) y "authenticated".
-- UNA sola base para TODOS los bares: cada fila de cada tabla lleva el
-- bar al que pertenece (bar_id) y las funciones de seguridad.sql nunca
-- dejan ver ni tocar lo de otro bar. La Mar de Gambas es el bar nº 1.
-- Este archivo crea las tablas desde cero. Para recrear la base en otro
-- sitio (por ejemplo Supabase) se ejecuta en este orden:
--   1. datos/esquema.sql           (tablas, este archivo)
--   2. datos/datos-iniciales.sql   (bar nº 1, pestañas, 139 productos y mesas)
--   3. datos/seguridad.sql         (permisos y reglas por rol, Fase 3)
--
-- Seguridad: todas las tablas nacen con seguridad por fila (RLS) activada
-- y sin ningún permiso para el público. Hasta que se aplique
-- seguridad.sql, nadie puede leer ni escribir nada desde la web.
--
-- No se guardan datos personales de clientes: un pedido solo lleva la
-- mesa y una "clave de dispositivo" al azar que genera el móvil.
--
-- Tras cambiar el esquema, esperar 30–60 s antes de probar desde la web
-- (la Data API tarda en enterarse de los cambios).
-- =====================================================================

-- ---------------- CARPETAS (esquemas) DE LA BASE · 17 oct ----------------
-- Una sola base para todos los productos de autonomIA Lab, ordenada en
-- carpetas (ver CLAUDE.md, «Arquitectura»):
--   comun        → lo compartido por todos los productos (negocios, personal y login)
--   multibar     → lo propio de MultiBar (carta, mesas, pedidos, avisos…)
--   autonomialab → la gestión de la empresa (de momento vacía)
-- Ninguna se publica en la web (Supabase solo publica «public», donde
-- están las funciones que llama la web).
create schema if not exists comun;
create schema if not exists multibar;
create schema if not exists autonomialab;
revoke all on schema comun, multibar, autonomialab from public;
set search_path = multibar, comun, public;
-- Desde el 18 oct (paso 2): lo común (negocios, usuarios) en «comun» y lo de
-- MultiBar con el sufijo _multibar en «multibar» (regla de nombres de PLATAFORMA.md).

-- ---------------- NEGOCIOS (comun: lo de todos los productos) ----------------
-- Cada cliente de la plataforma (un bar, un gimnasio…): su dirección corta
-- (slug, va en los enlaces y QR: /carta/?bar=lamardegambas&mesa=5&c=CODIGO),
-- su nombre (se escribe UNA vez aquí), su tipo de producto, su titular
-- (aviso legal) y sus «datos extra» (lo que solo tiene ese negocio).
-- Un negocio con activo = false no enseña nada ni deja entrar al personal.
-- La personalización de cada producto va en su carpeta (MultiBar:
-- multibar.ajustes_multibar).
create table comun.negocios (
  id               integer generated by default as identity primary key,
  slug             text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,39}$'),
  nombre           text not null,                 -- 'La Mar de Gambas'
  tipo             text not null default 'multibar', -- producto del negocio
  activo           boolean not null default true,
  zona_horaria     text not null default 'Europe/Madrid', -- para "pedidos de hoy"
  idioma           text not null default 'es',
  logo             text,                          -- identidad mínima (correos, panel de plataforma)
  titular          text,                          -- aviso legal: razón social o nombre
  nif              text,
  domicilio_fiscal text,
  correo_legal     text,
  telefono_legal   text,
  registro         text,                          -- datos registrales (sociedades)
  datos_extra      jsonb not null default '{}'::jsonb,
  created_at       timestamptz not null default now(),
  baja_at          timestamptz
);

-- Qué productos tiene contratados cada negocio.
create table comun.productos_contratados (
  negocio_id  integer not null references comun.negocios(id),
  producto    text not null,                    -- 'multibar', 'gimnasio'…
  activo      boolean not null default true,
  desde       timestamptz not null default now(),
  primary key (negocio_id, producto)
);

-- ---------------- AJUSTES DE MULTIBAR DE CADA BAR ----------------
-- Toda la personalización y las opciones de MultiBar de cada bar: subtítulo,
-- pie de la carta, aspecto (colores, fuentes, logo, textos), barra_cocina,
-- avisos_mesa, cuentas_mesa, control_mesas, numeración…
create table multibar.ajustes_multibar (
  negocio_id  integer primary key references comun.negocios(id),
  subtitulo   text not null default '',          -- 'Cervecerías · Desde 2007'
  ajustes     jsonb not null default '{}'::jsonb
);

-- ---------------- PESTAÑAS DE LA CARTA ----------------
-- El id de la pestaña ('mar', 'picar'…) solo tiene que ser único dentro
-- de cada bar: dos bares pueden tener cada uno su pestaña 'postres'.
create table multibar.categorias_multibar (
  negocio_id      integer not null references comun.negocios(id),
  id          text not null,                   -- 'mar', 'picar', 'bodega'…
  name        text not null,                   -- 'MARISCO Y MAR'
  sort_order  integer not null default 0,
  multi       boolean not null default false,  -- agrupa varias secciones de la carta física
  fam         text not null default '',        -- 'tp' = Tapa/Plato, 'cb' = Copa/Botella
  labs        text[] not null default '{}',    -- tamaños que usa la pestaña
  destino     text not null default 'cocina'   -- a quién van sus pedidos con «barra y cocina» (v15)
              check (destino in ('barra','cocina')),
  horario     jsonb,                           -- carta por horario (v25): {"dias":[1..7],"tramos":[{"desde":"13:00","hasta":"16:00"}]}; null = siempre
  primary key (negocio_id, id)
);

-- ---------------- PRODUCTOS ----------------
-- Cada tamaño es una fila propia (Croquetas Tapa y Croquetas Plato son
-- dos productos con su precio), igual que en la carta.
create table multibar.productos_multibar (
  id            integer generated by default as identity primary key,
  negocio_id        integer not null references comun.negocios(id),
  category_id   text not null,
  name          text not null,                 -- nombre con tamaño: 'Croquetas de puchero (Tapa)'
  display_name  text,                          -- nombre sin tamaño para agrupar: 'Croquetas de puchero'
  description   text not null default '',      -- '200 gr', '5 uds'…
  size          text check (size in ('Tapa','Plato','Copa','Botella')),
  only_size     boolean not null default false, -- solo existe en ese tamaño
  section       text not null default '',      -- sección original de la carta física
  price         numeric(7,2) not null check (price >= 0 and price < 1000),
  available     boolean not null default true,  -- false = AGOTADO (lo cambia barra o admin)
  visible       boolean not null default true,  -- false = no sale en la carta (lo cambia admin)
  featured      boolean not null default false, -- estrella "lo mejor de la casa"
  allergens     text[],                         -- pendiente: lista del local
  racion        text check (char_length(racion) <= 40), -- «para 2–3 personas» (v30, opción raciones)
  photo         text not null default '',
  sort_order    integer not null default 0,
  updated_at    timestamptz not null default now(),
  updated_by    text,                           -- usuario del personal que lo cambió
  marca         text check (marca in ('recomendado','del_dia','nuevo')), -- recomendados (v25): etiqueta en la carta
  foreign key (negocio_id, category_id) references categorias_multibar(negocio_id, id)
);
create index productos_multibar_category_idx on productos_multibar (negocio_id, category_id, sort_order);

-- ---------------- MESAS ----------------
-- "code" es el código secreto que va en el QR de cada mesa
-- (/carta/?bar=…&mesa=5&c=CODIGO). La base solo acepta pedidos si coincide.
-- El número de mesa solo es único dentro de cada bar (todos tienen Mesa 1).
-- Si se cambia, hay que reimprimir el QR de esa mesa.
-- Los códigos NO se guardan en el repositorio: los genera la base.
create table multibar.mesas_multibar (
  negocio_id      integer not null references comun.negocios(id),
  id          integer not null check (id between 1 and 999),  -- número de mesa
  name        text not null,                   -- 'Mesa 5', 'Terraza 2'…
  active      boolean not null default true,   -- false = no admite pedidos
  code        text not null default substr(replace(gen_random_uuid()::text, '-', ''), 1, 8),
  abierta_hasta timestamptz,                   -- "control de mesas": la mesa admite pedidos hasta esta hora (null = cerrada)
  created_at  timestamptz not null default now(),
  primary key (negocio_id, id)
);

-- ---------------- PEDIDOS ----------------
-- Estados: enviado (NUEVO: lo manda el cliente) → en_preparacion (lo acepta
-- el personal, o solo a los 3 minutos si nadie lo acepta) → servido.
-- "Deshacer" vuelve un paso atrás.
create table multibar.pedidos_multibar (
  id            bigint generated always as identity primary key,
  negocio_id        integer not null references comun.negocios(id),
  mesa_id       integer not null,
  round_number  integer not null default 1,     -- "Pedido 1, 2…" de ese móvil
  numero        integer,                        -- "Pedido nº N" del panel: cuenta propia de cada bar (la pone la base)
  destino       text check (destino in ('barra','cocina')), -- con «barra y cocina»: a quién va esta parte (v15)
  parte_de      bigint,                         -- 2.ª parte de un pedido dividido: id de la 1.ª (mismo número)
  cobrado_at    timestamptz,                    -- cuenta de la mesa cobrada (v15)
  cobrado_por   text,
  status        text not null default 'enviado'
                check (status in ('enviado','en_preparacion','servido')),
  total         numeric(8,2) not null default 0 check (total >= 0),
  device_key    uuid not null,                  -- número al azar del móvil (no es dato personal)
  created_at    timestamptz not null default now(),
  modified_at   timestamptz,                    -- última edición del cliente
  nuevo_desde   timestamptz not null default now(), -- desde cuándo está NUEVO (cuenta 3 min)
  auto_aceptado boolean not null default false,  -- pasó solo a preparación (nadie lo aceptó)
  received_at   timestamptz,                    -- cuándo pasó a "en preparación"
  received_by   text,                           -- quién lo aceptó
  served_at     timestamptz,
  served_by     text,
  desde_panel   boolean not null default false, -- lo metió el personal desde el panel (no ahorra viaje al camarero; v22)
  foreign key (negocio_id, mesa_id) references mesas_multibar(negocio_id, id)
);
create index pedidos_multibar_status_idx on pedidos_multibar (status, created_at);
create index pedidos_multibar_mesa_idx on pedidos_multibar (negocio_id, mesa_id, created_at);
create index pedidos_multibar_device_idx on pedidos_multibar (device_key, created_at);
create index pedidos_multibar_created_idx on pedidos_multibar (negocio_id, created_at);

-- ---------------- LÍNEAS DE CADA PEDIDO ----------------
-- Se copian nombre, tamaño y precio en el momento del pedido, para que
-- un cambio de precio posterior no altere pedidos ya hechos.
create table multibar.lineas_pedido_multibar (
  id            bigint generated always as identity primary key,
  order_id      bigint not null references pedidos_multibar(id) on delete cascade,
  product_id    integer not null references productos_multibar(id),
  product_name  text not null,
  size          text,
  unit_price    numeric(7,2) not null check (unit_price >= 0),
  quantity      integer not null check (quantity between 0 and 20), -- 0 = quitado por el personal (se ve en gris)
  note          text not null default '' check (char_length(note) <= 140)
);
create index lineas_pedido_multibar_order_idx on lineas_pedido_multibar (order_id);

-- ---------------- AVISOS DE LA MESA (v15) ----------------
-- «Llamar al camarero» y «Pedir la cuenta» desde la carta (opción del bar
-- ajustes.avisos_mesa). Salen en el panel hasta que alguien pulsa
-- «Atendido». No llevan datos personales (solo mesa, tipo y hora); el
-- panel solo enseña los de las últimas 12 h.
create table multibar.avisos_multibar (
  id            bigint generated always as identity primary key,
  negocio_id        integer not null references comun.negocios(id),
  mesa_id       integer not null,
  tipo          text not null check (tipo in ('camarero','cuenta')),
  created_at    timestamptz not null default now(),
  atendido_at   timestamptz,
  atendido_por  text,
  foreign key (negocio_id, mesa_id) references mesas_multibar(negocio_id, id)
);
create index avisos_multibar_bar_idx on avisos_multibar (negocio_id, created_at);

-- ---------------- USUARIOS (comun: el login de todos los productos) ----------------
-- Quién es cada persona. La contraseña se guarda cifrada (bcrypt, nunca en
-- claro). Un usuario con active = false no puede entrar. Cada cuenta es de
-- UN solo negocio y el correo es único en toda la plataforma (al entrar,
-- el correo dice de qué negocio es). El login es propio de la base (sin
-- cookies, igual en iPhone y Android): ver datos/funciones.sql.
create table comun.usuarios (
  id                    integer generated always as identity primary key,
  negocio_id            integer not null references comun.negocios(id),
  email                 text not null,
  name                  text not null,
  active                boolean not null default true,
  password_hash         text not null,
  must_change_password  boolean not null default true,  -- contraseña provisional
  failed_attempts       integer not null default 0,      -- intentos fallidos seguidos
  locked_until          timestamptz,                     -- bloqueo tras 5 fallos
  created_at            timestamptz not null default now()
);
create unique index usuarios_email_idx on comun.usuarios (lower(email));

-- ---------------- PERSONAL DE MULTIBAR (su rol en el bar) ----------------
create table multibar.personal_multibar (
  usuario_id  integer primary key references comun.usuarios(id) on delete cascade,
  negocio_id  integer not null references comun.negocios(id),
  role        text not null check (role in ('camarero','barra','admin'))
);

-- ---------------- VISTAS DE MULTIBAR (solo lectura, para sus funciones) ----------------
-- El bar tal como lo ve MultiBar: lo común + sus ajustes. Los datos del
-- titular se ofrecen dentro de ajustes.legal, como antes (página legal).
create view multibar.bares_multibar as
  select n.id, n.slug, n.nombre, coalesce(a.subtitulo, '') as subtitulo, n.zona_horaria, n.activo,
         coalesce(a.ajustes, '{}'::jsonb) || case when n.titular is null then '{}'::jsonb
           else jsonb_build_object('legal', jsonb_strip_nulls(jsonb_build_object(
             'titular', n.titular, 'nif', n.nif, 'domicilio', n.domicilio_fiscal,
             'email', n.correo_legal, 'telefono', n.telefono_legal, 'registro', n.registro))) end as ajustes,
         n.created_at
    from comun.negocios n left join multibar.ajustes_multibar a on a.negocio_id = n.id
   where n.tipo = 'multibar';  -- el negocio de la plataforma (autonomIA Lab) no es un bar (v27)

-- El personal tal como lo ve MultiBar: la persona + su rol en el bar.
create view multibar.usuarios_multibar as
  select u.id, u.negocio_id, u.email, u.name, p.role, u.active, u.password_hash,
         u.must_change_password, u.failed_attempts, u.locked_until, u.created_at
    from comun.usuarios u join multibar.personal_multibar p on p.usuario_id = u.id;

-- ---------------- SEGURIDAD BÁSICA (hasta la Fase 3) ----------------
-- Seguridad por fila activada en todas las tablas y ningún permiso para
-- la web. Los permisos por rol se dan en datos/seguridad.sql.
alter table comun.negocios             enable row level security;
alter table comun.productos_contratados enable row level security;
alter table multibar.ajustes_multibar  enable row level security;
alter table comun.usuarios             enable row level security;
alter table multibar.personal_multibar enable row level security;
alter table categorias_multibar  enable row level security;
alter table productos_multibar    enable row level security;
alter table mesas_multibar       enable row level security;
alter table pedidos_multibar      enable row level security;
alter table lineas_pedido_multibar enable row level security;
alter table avisos_multibar      enable row level security;

revoke all on all tables in schema comun, multibar from public, anon, authenticated;
-- Supabase da por defecto permisos a anon/authenticated en todo lo nuevo
-- del esquema public: se quitan (tablas, secuencias y funciones).
revoke all on all sequences in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
alter default privileges in schema public revoke execute on functions from public, anon, authenticated;
